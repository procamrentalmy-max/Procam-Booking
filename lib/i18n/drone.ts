const TEXTS: Record<Locale, DroneText> = { en: droneEn, ms: droneMs, zh: droneZh };

export function droneText(locale: Locale): DroneText {
  return TEXTS[locale] ?? TEXTS[DEFAULT_LOCALE];
}

/** The message for a form field that failed validation (zod reports which field), in the visitor's language. */
export function fieldError(errors: DroneText["errors"], field: unknown): string {
  switch (field) {
    case "name":
      return errors.name;
    case "phone":
      return errors.phone;
    case "email":
      return errors.email;
    case "durationMinutes":
      return errors.rentalLength;
    default:
      return errors.details;
  }
}

/** "Today", "Tomorrow", then "Mon 5 Oct" (in the visitor's language) for the day picker, in Malaysia time. */
export function dayLabelFor(now: Date, dayOffset: number, locale: Locale): string {
  const t = droneText(locale);
  if (dayOffset === 0) return t.common.today;
  if (dayOffset === 1) return t.common.tomorrow;
  const day = new Date(now.getTime() + dayOffset * 24 * 60 * 60_000);
  return day.toLocaleDateString(INTL_TAGS[locale], { timeZone: "Asia/Kuala_Lumpur", weekday: "short", day: "numeric", month: "short" });
}

/** A rental length for a customer ("1h 30m", in their language) from milliseconds. */
export function durationLabel(ms: number, locale: Locale): string {
  return droneText(locale).common.duration(Math.max(0, Math.round(ms / 60_000)));
}

/** "Phone only", or the controller's own name (RC-N3, Goggles N3 + Motion 3: product names, never translated). */
export function controllerNameFor(shortName: string | undefined, locale: Locale): string {
  return shortName ?? droneText(locale).common.phoneOnly;
}
